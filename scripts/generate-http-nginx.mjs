// Keep the Tailnet HTTP override in sync with the canonical TLS configuration.
import { readFile, writeFile } from 'node:fs/promises'
const source = new URL('../deployment/nginx/default.conf', import.meta.url)
const target = new URL('../deployment/nginx/default.http.conf', import.meta.url)
const config = (await readFile(source, 'utf8')).replace(/\r\n/g, '\n')
const firstServer = config.indexOf('server {\n')
const tlsStart = config.indexOf('server {\n    listen 443 ssl;')
if (firstServer < 0 || tlsStart < 0) throw new Error('Expected canonical HTTP redirect and TLS server')
const prefix = config.slice(0, firstServer)
const tls = config.slice(tlsStart)
const http = tls.split('\n').filter(line => {
  const value = line.trim()
  return !value.startsWith('ssl_') && value !== 'http2 on;' && !value.startsWith('error_page 497 ') && !value.startsWith('add_header Strict-Transport-Security ')
}).join('\n').replace('listen 443 ssl;', 'listen 80;').replace('listen [::]:443 ssl;', 'listen [::]:80;').replaceAll('proxy_set_header X-Forwarded-Proto https;', 'proxy_set_header X-Forwarded-Proto http;')
await writeFile(target, prefix + '# Generated by scripts/generate-http-nginx.mjs. Serve HTTP for the Tailnet port override.\n' + http + '\n' + tls)
console.log('Generated deployment/nginx/default.http.conf')
